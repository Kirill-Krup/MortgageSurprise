-- V1: Initial Database Schema for MortgageSurprise

CREATE TABLE age_rules
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_age        INT     NOT NULL,
    max_age        INT     NOT NULL,
    rule_type      VARCHAR NOT NULL,
    credit_scoring FLOAT   NOT NULL,
    is_active      BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT chk_age CHECK (min_age <= max_age),
    CONSTRAINT uq_age_range_per_rule UNIQUE (rule_type, min_age, max_age)
);

CREATE TABLE gender_rules
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR NOT NULL,
    rule_type      VARCHAR NOT NULL,
    credit_scoring FLOAT   NOT NULL,
    is_active      BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT uq_gender_rules_name_per_type
        UNIQUE (rule_type, name)
);

CREATE TABLE country_rules
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code   VARCHAR(3) NOT NULL,
    rule_type      VARCHAR    NOT NULL,
    credit_scoring FLOAT      NOT NULL,
    is_active      BOOLEAN    NOT NULL DEFAULT true,
    CONSTRAINT uq_country_rules_code_per_type
        UNIQUE (rule_type, country_code)
);

CREATE TABLE city_rules
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name      VARCHAR NOT NULL,
    rule_type      VARCHAR NOT NULL,
    credit_scoring FLOAT   NOT NULL,
    is_active      BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT uq_city_rules_name_per_type
        UNIQUE (rule_type, city_name)
);